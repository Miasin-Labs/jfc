#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultInput = path.join(
  process.env.HOME ?? "",
  "VulnerabilityResearch/anthropic/binaries/latest/cli.deobfuscated.js",
);
const input = path.resolve(process.argv[2] ?? process.env.CLAUDE_DEOBFUSCATED ?? defaultInput);
const output = path.join(
  root,
  "crates/jfc-provider/src/anthropic_catalog_generated.rs",
);

function extractCatalog(source) {
  const marker = '"Hand-maintained baked-in model catalog';
  const markerAt = source.indexOf(marker);
  if (markerAt < 0) throw new Error(`catalog marker not found in ${input}`);
  const assignmentAt = source.lastIndexOf("D3a = {", markerAt);
  if (assignmentAt < 0) throw new Error("catalog assignment not found");
  const start = source.indexOf("{", assignmentAt);
  let depth = 0;
  let quote = null;
  let escaped = false;
  for (let i = start; i < source.length; i += 1) {
    const char = source[i];
    if (quote !== null) {
      if (escaped) escaped = false;
      else if (char === "\\") escaped = true;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === '"' || char === "'" || char === "`") quote = char;
    else if (char === "{") depth += 1;
    else if (char === "}" && --depth === 0) {
      return vm.runInNewContext(`(${source.slice(start, i + 1)})`, Object.create(null), {
        timeout: 1_000,
      });
    }
  }
  throw new Error("unterminated model catalog object");
}

function rustString(value) {
  return JSON.stringify(value);
}

function rustOption(value) {
  return value == null ? "None" : `Some(${rustString(value)})`;
}

function rustFloat(value) {
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function rustKind(id) {
  const parts = id.replace(/^claude-/, "").split("-");
  const family = parts.includes("opus")
    ? "Opus"
    : parts.includes("sonnet")
      ? "Sonnet"
      : parts.includes("haiku")
        ? "Haiku"
        : parts[0][0].toUpperCase() + parts[0].slice(1);
  const version = parts
    .filter((part) => /^\d+$/.test(part))
    .join("")
    .replace(/^40$/, "4");
  return `${family}${version}`;
}

function firstPartyAlias(catalog, alias) {
  const id = catalog.aliases[alias].default;
  const model = catalog.models.find((candidate) => candidate.id === id);
  if (!model) throw new Error(`alias ${alias} points at unknown model ${id}`);
  return model.provider_ids.first_party;
}

function render(catalog) {
  const lines = [
    "// @generated by scripts/sync-anthropic-model-catalog.mjs. Do not edit by hand.",
    "",
    `pub const ANTHROPIC_ALIAS_OPUS: &str = ${rustString(firstPartyAlias(catalog, "opus"))};`,
    `pub const ANTHROPIC_ALIAS_SONNET: &str = ${rustString(firstPartyAlias(catalog, "sonnet"))};`,
    `pub const ANTHROPIC_ALIAS_HAIKU: &str = ${rustString(firstPartyAlias(catalog, "haiku"))};`,
    `pub const ANTHROPIC_ALIAS_FABLE: &str = ${rustString(firstPartyAlias(catalog, "fable"))};`,
    "",
    "#[rustfmt::skip]",
    "pub const ANTHROPIC_MODEL_CATALOG: &[AnthropicModelMetadata] = &[",
  ];

  for (const model of catalog.models) {
    const pricing =
      typeof model.pricing === "string"
        ? catalog.pricing_tiers[model.pricing]
        : model.pricing;
    const context = model.context ?? {};
    const ids = model.provider_ids;
    lines.push(
      "    AnthropicModelMetadata {",
      `        id: ${rustString(model.id)},`,
      `        kind: AnthropicModelKind::${rustKind(model.id)},`,
      `        family: ${rustString(model.family)},`,
      `        display_name: ${rustString(model.display_name)},`,
      "        provider_ids: AnthropicProviderIds {",
      `            first_party: ${rustString(ids.first_party)},`,
      `            bedrock: ${rustOption(ids.bedrock)},`,
      `            vertex: ${rustOption(ids.vertex)},`,
      `            foundry: ${rustOption(ids.foundry)},`,
      `            anthropic_aws: ${rustOption(ids.anthropic_aws)},`,
      `            mantle: ${rustOption(ids.mantle)},`,
      `            gateway: ${rustOption(ids.gateway)},`,
      "        },",
      `        context_window_tokens: ${context.window ?? 200_000},`,
      `        max_output_tokens: ${model.max_output_tokens.upper},`,
      `        input_cost: ${rustFloat(pricing.input)},`,
      `        output_cost: ${rustFloat(pricing.output)},`,
      `        supports_1m_beta: ${context.supports_1m_beta === true},`,
      `        supports_1m_suffix: ${context.supports_1m_suffix === true},`,
      `        native_1m: ${context.native_1m === true},`,
      `        capabilities: &[${model.capabilities.map(rustString).join(", ")}],`,
      "    },",
    );
  }
  lines.push("];", "");
  return lines.join("\n");
}

const generated = render(extractCatalog(fs.readFileSync(input, "utf8")));
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== generated) {
    console.error(`${path.relative(root, output)} is stale; rerun ${path.basename(process.argv[1])}`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(output, generated);
  console.log(`updated ${path.relative(root, output)} from ${input}`);
}
